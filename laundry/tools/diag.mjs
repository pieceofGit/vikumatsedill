// Temporary: checks how ntfy.sh handles scheduled messages with sequence IDs.
const T = 'vk-diag-' + Math.random().toString(36).slice(2, 10)
const sleep = ms => new Promise(r => setTimeout(r, ms))
const show = async (label, res) => console.log(`--- ${label}: ${res.status}\n${(await res.text()).slice(0, 2500)}`)
const at = Math.floor(Date.now() / 1000) + 75
await show('cmd GET publish', await fetch(`https://ntfy.sh/${T}-cmd/publish?title=laundry-x.washer.10&message=2%20hours`))
await show('schedule washer-1 (+75s)', await fetch(`https://ntfy.sh/${T}/washer-1?at=${at}&title=one`, { method: 'POST', body: 'one' }))
await show('schedule washer-2 (+80s)', await fetch(`https://ntfy.sh/${T}/washer-2?at=${at + 5}&title=two`, { method: 'POST', body: 'two' }))
await sleep(8000)
await show('cmd poll since=1h (after 8s)', await fetch(`https://ntfy.sh/${T}-cmd/json?poll=1&since=1h`))
await show('cmd poll since=all', await fetch(`https://ntfy.sh/${T}-cmd/json?poll=1&since=all`))
await show('poll sched=1', await fetch(`https://ntfy.sh/${T}/json?poll=1&sched=1`))
await show('poll since=all&sched=1', await fetch(`https://ntfy.sh/${T}/json?poll=1&since=all&sched=1`))
await show('DELETE washer-1', await fetch(`https://ntfy.sh/${T}/washer-1`, { method: 'DELETE' }))
await sleep(5000)
await show('poll since=all&sched=1 after delete', await fetch(`https://ntfy.sh/${T}/json?poll=1&since=all&sched=1`))
await sleep(85000)
await show('poll since=all after both due (washer-1 should be gone, washer-2 delivered)', await fetch(`https://ntfy.sh/${T}/json?poll=1&since=all`))
